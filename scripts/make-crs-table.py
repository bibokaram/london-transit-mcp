"""Regenerate src/data/crs.ts: National Rail CRS code -> TfL station ID (910G...).

TfL's stop search cannot resolve CRS codes, so the timetable tool uses this table.
Source: DfT NaPTAN, rail access nodes (ATCO area 910), whose XML carries each station's CrsRef.

    curl -o rail.xml 'https://naptan.api.dft.gov.uk/v1/access-nodes?dataFormat=xml&atcoAreaCodes=910'
    python3 scripts/make-crs-table.py rail.xml src/data/crs.ts
"""
import sys
import xml.etree.ElementTree as ET

NS = {'n': 'http://www.naptan.org.uk/'}
table = {}
for _, element in ET.iterparse(sys.argv[1]):
    if element.tag.endswith('}StopPoint'):
        atco = element.findtext('n:AtcoCode', namespaces=NS) or ''
        crs = element.findtext('.//n:CrsRef', namespaces=NS)
        if crs and atco.startswith('9100') and element.get('Status', 'active') == 'active':
            table.setdefault(crs.strip().upper(), '910G' + atco[4:])
        element.clear()
pairs = ' '.join(f'{crs}:{station[4:]}' for crs, station in sorted(table.items()))
with open(sys.argv[2], 'w') as out:
    out.write('// Generated by scripts/make-crs-table.py from DfT NaPTAN rail data. Do not edit by hand.\n')
    out.write('// National Rail CRS code -> TfL station ID suffix; the full ID is "910G" + suffix.\n')
    out.write(f"export const CRS_TABLE = '{pairs}';\n")
print(f'{len(table)} stations')
